#!/usr/bin/env python3
"""Regenerate stepper/problems/manifest.js from the files in stepper/problems/.

Run after adding, renaming or deleting a problem file:
    python3 stepper/tools/build_manifest.py

Order: folders alphabetically (interview_challenges first), files alphabetically inside each folder.
The sidebar tree is built from each problem's `dir`, so file order only affects order within a folder.
To force an order, prefix file names (e.g. 01-foo.js) or add `order: N` in the problem object.
"""
import os, json

HERE = os.path.dirname(os.path.abspath(__file__))
PROBLEMS = os.path.normpath(os.path.join(HERE, '..', 'problems'))

def key(path):
    top = path.split('/')[0]
    return (0 if top == 'interview_challenges' else 1, path)

files = []
for root, _, names in os.walk(PROBLEMS):
    for n in names:
        if n.endswith('.js') and n != 'manifest.js' and not n.startswith('_'):
            files.append(os.path.relpath(os.path.join(root, n), PROBLEMS).replace(os.sep, '/'))
files.sort(key=key)

out = '/* AUTO-GENERATED by tools/build_manifest.py. Do not edit by hand. */\nwindow.PROBLEM_FILES = ' + json.dumps(['problems/' + f for f in files], indent=2) + ';\n'
open(os.path.join(PROBLEMS, 'manifest.js'), 'w', encoding='utf-8').write(out)
print(f'manifest.js: {len(files)} problem files')
